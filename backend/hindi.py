def amount_words(n: int) -> str:
    n = int(n)
    if n <= 0:
        return "शून्य"
    if n < 100:
        return ONES[n]
    if n < 1000:
        h, rest = divmod(n, 100)
        head = f"{ONES[h]} सौ"
        return f"{head} {ONES[rest]}".strip() if rest else head
    if n < 100000:
        th, rest = divmod(n, 1000)
        head = f"{ONES[th] if th < 100 else amount_words(th)} हज़ार"
        return f"{head} {amount_words(rest)}" if rest else head
    return str(n)


def announcement(amount: int) -> str:
    return f"पेटीएम पर {amount_words(amount)} रुपये प्राप्त हुए"
